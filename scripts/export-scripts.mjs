// Generates, from the content files (single source of truth):
//   docs/narration-scripts.md   recording script for every narrated scene + documentaries
//   docs/timing-plan.md         scene-by-scene run of show with start times
//   public/captions/doc1-5.vtt  WebVTT captions for the documentaries
// and fails if any script is too long for its scene.
// Run with: npm run export:scripts
import { readdir, writeFile, mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import path from 'node:path';

const root = path.resolve('.');
const imp = async (p) => import(pathToFileURL(path.join(root, p)).href);

const { NARRATION, spokenText, WORDS_PER_MINUTE } = await imp('src/data/narration.js');
const { DOCUMENTARIES } = await imp('src/data/documentaries.js');
const { GAMES } = await imp('src/data/games.js');

const files = (await readdir(path.join(root, 'src/sections'))).filter((f) => /^part\d/.test(f)).sort();
const parts = [];
for (const f of files) parts.push((await imp(`src/sections/${f}`)).default);

const fmt = (s) => `${Math.floor(s / 60)}:${String(Math.round(s % 60)).padStart(2, '0')}`;
const words = (t) => spokenText(t).split(/\s+/).filter(Boolean).length;
const secsFor = (w) => (w / WORDS_PER_MINUTE) * 60;
const label = (s) =>
  s.layout === 'documentary' ? `Documentary ${s.docId}: ${DOCUMENTARIES[s.docId].title}` : s.layout === 'game' ? `Game ${s.gameId}: ${GAMES[s.gameId].title}` : s.title;

let problems = [];

// ---------- narration-scripts.md ----------
let md = `# Narration scripts

Generated from \`src/data/narration.js\` and \`src/data/documentaries.js\` by
\`npm run export:scripts\`. Edit those files, not this one.

## Recording guide

- **Format:** MP3, mono, 44.1 kHz, 128 kbps or higher. Save in \`public/audio/narration/\` with the exact file name below.
- **Pace:** about ${WORDS_PER_MINUTE} words per minute, calm and clear. Read time below is estimated at that pace.
- **Room:** quiet room, same microphone and distance for every file. Leave about half a second of silence at the start and end.
- **Stage directions** in [square brackets] are for the presenter clicking along. Don't read them aloud.
- **Documentaries:** record each one as a single file (\`doc1.mp3\` to \`doc5.mp3\`). Start each line at the time shown so captions line up, or record naturally and send the times so the beats can be adjusted.
- **Check:** after adding files, run the presentation. The dock says "Voice playing" instead of "Voice pending".

| Scene | File | Planned | Words | Est. read |
|---|---|---|---|---|
`;

const sections = [];
for (const part of parts) {
  let block = `\n## Part ${part.id} · ${part.title}\n`;
  part.scenes.forEach((s, i) => {
    if (s.layout === 'game' || s.optional) return;
    if (s.layout === 'documentary') {
      const doc = DOCUMENTARIES[s.docId];
      const all = doc.beats.map((b) => b.caption).join(' ');
      const w = words(all);
      const est = secsFor(w);
      md += `| ${s.id} | \`${doc.audio}\` | ${fmt(doc.duration)} | ${w} | ${fmt(est)} |\n`;
      if (est > doc.duration) problems.push(`${s.id}: documentary script ${fmt(est)} is longer than ${fmt(doc.duration)}`);
      block += `\n### ${s.id} · Documentary: ${doc.title}\n\nFile \`${doc.audio}\` · ${fmt(doc.duration)} · ${w} words\n\n`;
      doc.beats.forEach((b) => {
        block += `- **${fmt(b.t)}** (on screen: “${b.text}”) ${b.caption}\n`;
      });
      return;
    }
    const text = NARRATION[s.id];
    const file = `p${part.id}-s${i + 1}.mp3`;
    if (!text) {
      problems.push(`${s.id}: no narration script`);
      return;
    }
    const w = words(text);
    const est = secsFor(w);
    md += `| ${s.id} | \`${file}\` | ${fmt(s.duration)} | ${w} | ${fmt(est)} |\n`;
    if (est > s.duration) problems.push(`${s.id}: script reads ${fmt(est)} but scene is ${fmt(s.duration)}`);
    block += `\n### ${s.id} · ${s.title}\n\nFile \`${file}\` · ${fmt(s.duration)} · ${w} words\n\n> ${text.replace(/\[([^\]]*)\]/g, '*[$1]*')}\n`;
  });
  sections.push(block);
}
md += sections.join('');

// ---------- timing-plan.md ----------
let tp = `# Timing plan

Generated by \`npm run export:scripts\` from the scene durations in \`src/sections/\`.
Approved run of show: 28:00 of scenes + 2:00 transitions/contingency = **30:00**.
Narration is the recorded voice; the rest of each scene is interaction, games or video.

| Start | Scene | Type | Planned | Narration |
|---|---|---|---|---|
`;
let clock = 0;
for (const part of parts) {
  const ps = part.scenes.reduce((t, s) => t + (s.duration || 0), 0);
  tp += `| **${fmt(clock)}** | **Part ${part.id} · ${part.title}** | | **${fmt(ps)}** | |\n`;
  for (const s of part.scenes) {
    const type = s.layout === 'documentary' ? 'Documentary' : s.layout === 'game' ? 'Educaplay game' : s.optional ? 'Optional (not timed)' : s.layout;
    let narr = '—';
    if (s.layout === 'documentary') narr = fmt(secsFor(words(DOCUMENTARIES[s.docId].beats.map((b) => b.caption).join(' '))));
    else if (NARRATION[s.id]) narr = fmt(secsFor(words(NARRATION[s.id])));
    tp += `| ${fmt(clock)} | ${s.id} ${label(s)} | ${type} | ${s.duration ? fmt(s.duration) : '—'} | ${narr} |\n`;
    clock += s.duration || 0;
  }
}
tp += `| ${fmt(clock)} | Transitions / contingency (spread across the session) | | 2:00 | |\n| **${fmt(clock + 120)}** | **End** | | | |\n`;
tp += `\nThe optional live demo (4.x, prompts in Reference R6) adds 3–5 minutes and is not included.\n`;

// ---------- VTT captions ----------
const vttTime = (s) => {
  const ms = Math.round(s * 1000);
  const h = String(Math.floor(ms / 3600000)).padStart(2, '0');
  const m = String(Math.floor((ms % 3600000) / 60000)).padStart(2, '0');
  const sec = String(Math.floor((ms % 60000) / 1000)).padStart(2, '0');
  return `${h}:${m}:${sec}.${String(ms % 1000).padStart(3, '0')}`;
};
await mkdir(path.join(root, 'public/captions'), { recursive: true });
for (const [id, doc] of Object.entries(DOCUMENTARIES)) {
  let vtt = 'WEBVTT\n\n';
  doc.beats.forEach((b, i) => {
    const end = i + 1 < doc.beats.length ? doc.beats[i + 1].t : doc.duration;
    vtt += `${i + 1}\n${vttTime(b.t)} --> ${vttTime(end)}\n${b.caption}\n\n`;
  });
  await writeFile(path.join(root, `public/captions/doc${id}.vtt`), vtt);
}

// ---------- game-content.md ----------
const { isEducaplayUrl } = await imp('src/data/games.js');
let gm = `# Educaplay game content

Generated from \`src/data/games.js\` by \`npm run export:scripts\`. Edit that file, not this one.

## How to publish each game

1. Sign in at https://www.educaplay.com and choose **Create activity**, then the type listed below.
2. Enter the title, then the questions and answers exactly as below (correct answers are **bold**).
3. Set a short time limit so the game fits about 60 seconds, including joining. Use the first 3 questions if time is short.
4. Publish it as **public** (or "anyone with the link").
5. Copy the activity's public link into \`url\` for that game in \`src/data/games.js\`.
   Optional: from Share → Embed, copy the embed link into \`embedUrl\` to enable **Play here**.
6. Open the game slide: the QR code and Launch / Copy link buttons switch on automatically.
7. Test the link on a phone and a laptop as a participant, then tick it off in the status table.

Only \`https://…educaplay.com\` links are accepted; any other link is ignored and flagged on the slide.
Game 7 uses **Froggy Jumps**, which Educaplay lists as supporting live multiplayer sessions.

## Status

| Game | Slide | Type | Link |
|---|---|---|---|
`;
const gameSlides = {};
for (const part of parts) for (const s of part.scenes) if (s.layout === 'game') gameSlides[s.gameId] = s.id;
for (const [id, g] of Object.entries(GAMES)) {
  const st = isEducaplayUrl(g.url) ? g.url : g.url ? '⚠ not an Educaplay link' : 'Pending publication';
  gm += `| ${id} · ${g.title} | ${gameSlides[id]} | ${g.type} | ${st} |\n`;
}
for (const [id, g] of Object.entries(GAMES)) {
  gm += `\n## Game ${id} · ${g.title}\n\n**Slide:** ${gameSlides[id]} · **Type:** ${g.type}\n\n`;
  if (g.questions) {
    g.questions.forEach((q, i) => {
      if (q.answer < 0 || q.answer >= q.options.length) problems.push(`Game ${id} Q${i + 1}: answer index out of range`);
      gm += `${i + 1}. ${q.q}\n${q.options.map((o, j) => `   - ${j === q.answer ? `**${o}**` : o}`).join('\n')}\n   - *Why:* ${q.why}\n`;
    });
  }
  if (g.pairs) {
    gm += `| Task | Capability |\n|---|---|\n${g.pairs.map(([a, b]) => `| ${a} | ${b} |`).join('\n')}\n`;
  }
  gm += `\n**Backup question (spoken, if Educaplay or the internet fails):** ${g.backup.q}\n**Answer:** ${g.backup.a}\n\n**Presenter cue:** ${g.cue}\n`;
}
await writeFile(path.join(root, 'docs/game-content.md'), gm);

await writeFile(path.join(root, 'docs/narration-scripts.md'), md);
await writeFile(path.join(root, 'docs/timing-plan.md'), tp);

console.log('Wrote docs/narration-scripts.md, docs/timing-plan.md, docs/game-content.md, public/captions/doc1-5.vtt');
if (problems.length) {
  console.error('\nProblems:\n- ' + problems.join('\n- '));
  process.exit(1);
}
console.log('All scripts fit their scenes.');
